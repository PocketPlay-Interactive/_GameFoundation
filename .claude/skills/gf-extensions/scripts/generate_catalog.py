#!/usr/bin/env python3
"""Regenerate references/extensions.md from the GF extension sources.

Run from anywhere:  python .claude/skills/gf-extensions/scripts/generate_catalog.py
The output is overwritten; edit the source files, not the generated catalog.
"""
import os
import re
import sys

SKILL_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTENSIONS_REL = os.path.join("Runtime", "Core", "Utilities", "Extensions")
OUT_FILE = os.path.join(SKILL_DIR, "references", "extensions.md")


def find_source_dir():
    """Walk up from the skill folder and accept the first layout that contains the extensions.

    Supported layouts: the GF package repo itself (<root>/Runtime/...), a project that holds GF in
    Assets (<root>/Assets/_GameFoundation/Runtime/...), or a project that installed it as a package
    (<root>/Packages/com.dann.gamefoundation/Runtime/...). Git-installed packages live in
    Library/PackageCache and are read-only, so the catalog cannot be regenerated there.
    """
    layouts = [
        EXTENSIONS_REL,
        os.path.join("Assets", "_GameFoundation", EXTENSIONS_REL),
        os.path.join("Packages", "com.dann.gamefoundation", EXTENSIONS_REL),
    ]
    folder = SKILL_DIR
    while True:
        for layout in layouts:
            candidate = os.path.join(folder, layout)
            if os.path.isdir(candidate):
                return folder, candidate
        parent = os.path.dirname(folder)
        if parent == folder:
            return None, None
        folder = parent


REPO_ROOT, SOURCE_DIR = find_source_dir()

CLASS_RE = re.compile(r"^\s*public\s+static\s+class\s+(\w+)")
METHOD_RE = re.compile(r"^\s*public\s+static\s+(?!class\b)(?!readonly\b)(.+)$")


def read_lines(path):
    with open(path, "r", encoding="utf-8-sig") as handle:
        return handle.read().splitlines()


def signature(lines, index):
    """Return the declaration text up to the body or expression arrow."""
    text = lines[index].strip()
    # Join continuation lines until the parameter list is closed.
    while text.count("(") > text.count(")") and index + 1 < len(lines):
        index += 1
        text += " " + lines[index].strip()
    text = re.split(r"\s*(=>|\{)", text, maxsplit=1)[0].strip().rstrip(";")
    text = re.sub(r"\s+", " ", text).replace("( ", "(")
    return re.sub(r"^public\s+static\s+", "", text)


def summary_above(lines, index):
    """Return the XML <summary> directly above a declaration, if any.

    Plain // comments are ignored on purpose: in these files they usually label a whole group of
    methods, so attaching them to the next declaration would be misleading.
    """
    cursor = index - 1
    while cursor >= 0 and lines[cursor].strip().startswith("["):
        cursor -= 1
    block = []
    while cursor >= 0 and lines[cursor].strip().startswith("///"):
        block.append(lines[cursor].strip()[3:].strip())
        cursor -= 1
    text = " ".join(reversed(block))
    text = re.sub(r"<paramref\s+name=\"(\w+)\"\s*/>", r"\1", text)
    text = re.sub(r"<[^>]+>", "", text)
    return re.sub(r"\s+", " ", text).strip()


def is_obsolete(lines, index):
    cursor = index - 1
    while cursor >= 0 and lines[cursor].strip().startswith("["):
        if "Obsolete" in lines[cursor]:
            return True
        cursor -= 1
    return False


def main():
    if SOURCE_DIR is None:
        sys.exit(
            "Could not find " + EXTENSIONS_REL + " above " + SKILL_DIR + ". Run this script from a checkout "
            "of the GF repo or from a project that keeps GF in Assets or Packages."
        )

    out = [
        "# GF extension catalog",
        "",
        "Generated by `scripts/generate_catalog.py` from "
        "`Runtime/Core/Utilities/Extensions/`. Do not edit by hand.",
        "",
    ]
    total = 0
    for name in sorted(os.listdir(SOURCE_DIR)):
        if not name.endswith(".cs"):
            continue
        lines = read_lines(os.path.join(SOURCE_DIR, name))
        entries = []
        current_class = None
        for index, line in enumerate(lines):
            class_match = CLASS_RE.match(line)
            if class_match:
                current_class = class_match.group(1)
                continue
            method_match = METHOD_RE.match(line)
            if not method_match or current_class is None:
                continue
            sig = signature(lines, index)
            if "(" not in sig:
                continue
            note = summary_above(lines, index)
            tag = " **[deprecated]**" if is_obsolete(lines, index) else ""
            entries.append((current_class, sig, note, tag))
        if not entries:
            continue

        out.append("## " + name)
        out.append("")
        last_class = None
        for cls, sig, note, tag in entries:
            if cls != last_class:
                out.append("**" + cls + "**")
                out.append("")
                last_class = cls
            line = "- `" + sig + "`" + tag
            if note:
                line += " - " + note
            out.append(line)
            total += 1
        out.append("")

    os.makedirs(os.path.dirname(OUT_FILE), exist_ok=True)
    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out).rstrip() + "\n")
    print("Wrote {} entries to {}".format(total, os.path.relpath(OUT_FILE, REPO_ROOT)))


if __name__ == "__main__":
    main()
